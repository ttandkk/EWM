#!/usr/bin/env bash
# Eight dynamic and legacy Piper model evaluations, using the existing policy server + Isaac watchdog.
# Default: submit one GPU job. --plan-only validates/prints scenes on CPU only.
set -euo pipefail

script_path="$(realpath "${BASH_SOURCE[0]}")"
project_root="${EWM_PROJECT_ROOT:-$(cd -- "$(dirname -- "$script_path")/../../.." && pwd -P)}"
client="$project_root/OpenWAM/scripts/eval_ewm/eval_ewm_piper_tasks_sim.py"
checkpoint_dir="${EWM_CHECKPOINT_DIR:-}"
task=""
output_dir=""
condition="id"
rgb_mode="clean"
policy_mode=""
plan_only=0
latency=1
original_args=("$@")
client_args=()
while (($#)); do
    case "$1" in
        --help|-h)
            cat <<'HELP'
Usage: bash run_ewm_piper_tasks_eval.sh --task TASK --checkpoint-dir RUN [OPTIONS]
Tasks: conveyor moving_carton turntable_cups rotating_tube tennis_rolling tennis_falling tennis_parabolic tennis_container
Legacy: push_t drawer_cup square_nut
Default: 50 trials, task-specific time limit, buffered measured policy latency.
--condition id|lighting_ood|blur_ood|background_ood|speed_ood|slow|fast
                              speed_ood combines 25 slow + 25 fast trials (50 total).
--plan-only                   CPU validation/scene JSON; never submits a job.
--dataset-dir DATA            Training export (required without a checkpoint).
--output-dir OUT              Separate output directory for this evaluation.
--no-latency-aware            Inference-paused ablation, labeled separately.
--record-predictions          Default: append RGB/event forecasts after each trial, outside equivalent latency.
--no-record-predictions       Disable post-trial prediction recording.
--decode-predicted-events     Legacy inline event display when post-trial recording is disabled.
--rgb-ood-mode MODE           Existing stack RGB-only corruption ablation.
--scene-manifest JSON         Reuse a fixed scene list generated by --plan-only.
Other options are forwarded to eval_ewm_piper_tasks_sim.py (see its --help).
Environment: EWM_EVAL_GRES=gpu:l40:1, EWM_EVAL_PARTITION=cluster02,
EWM_EVAL_TIME=08:00:00, COMPILE_CORE=false, CACHE_CONTEXT_KV=true,
ALLOW_COMPILE_ACTION_ERROR=true (set false for strict error checking);
BENCHMARK_ITERS defaults to 1 when COMPILE_CORE=true, otherwise 0.
EWM_EVAL_DIRECT=1 runs on an already allocated GPU without submitting a job.
HELP
            exit 0 ;;
        --checkpoint-dir|--task|--output-dir|--condition|--rgb-ood-mode|--policy-mode)
            [[ $# -ge 2 && "$2" != --* ]] || { echo "Missing value for $1" >&2; exit 2; }
            case "$1" in
                --checkpoint-dir) checkpoint_dir="$2" ;;
                --task) task="$2" ;;
                --output-dir) output_dir="$2" ;;
                --condition) condition="$2"; client_args+=("$1" "$2") ;;
                --rgb-ood-mode) rgb_mode="$2"; client_args+=("$1" "$2") ;;
                --policy-mode) policy_mode="$2" ;;
            esac
            shift 2 ;;
        --plan-only) plan_only=1; shift ;;
        --no-latency-aware) latency=0; client_args+=("$1"); shift ;;
        --latency-aware) latency=1; client_args+=("$1"); shift ;;
        *) client_args+=("$1"); shift ;;
    esac
done
case "$task" in
    push_t|drawer_cup|square_nut|conveyor|moving_carton|turntable_cups|rotating_tube|tennis_rolling|tennis_falling|tennis_parabolic|tennis_container) ;;
    *) echo 'Pass --task with a supported Piper task name.' >&2; exit 2 ;;
esac
source "$project_root/migration/deploy_env.sh"
if [[ -n "$checkpoint_dir" ]]; then
    checkpoint_dir="$(realpath "$checkpoint_dir")"
    detected_mode="$("$OWPY" - "$checkpoint_dir/config.yaml" "$plan_only" <<'PY'
import sys
from pathlib import Path
from omegaconf import OmegaConf
mode = OmegaConf.load(sys.argv[1]).model.get('training_mode', 'joint')
if mode not in ('joint', 'action_only', 'rgb_action'):
    raise SystemExit('Piper evaluation supports joint, action_only and rgb_action policies.')
if sys.argv[2] != '1':
    root = Path(sys.argv[1]).parent
    if not (root/'normalization.json').is_file() or not any(root.glob('checkpoint_step_*.pt')):
        raise SystemExit('Evaluation requires normalization.json and checkpoint_step_*.pt before scheduling.')
print(mode)
PY
    )"
    if [[ -n "$policy_mode" && "$policy_mode" != "$detected_mode" ]]; then
        echo '--policy-mode differs from checkpoint training mode' >&2; exit 2
    fi
    policy_mode="$detected_mode"
fi
policy_mode="${policy_mode:-joint}"
base_args=(--task "$task" --policy-mode "$policy_mode")
if [[ -n "$checkpoint_dir" ]]; then base_args+=(--checkpoint-dir "$checkpoint_dir"); fi
if ((plan_only)); then
    exec "$OWPY" "$client" "${base_args[@]}" --plan-only "${client_args[@]}"
fi
if [[ -z "$checkpoint_dir" ]]; then echo 'Pass --checkpoint-dir or EWM_CHECKPOINT_DIR.' >&2; exit 2; fi
# Validate metadata, task/mode, time limits, and all client flags before scheduling.
"$OWPY" "$client" "${base_args[@]}" --plan-only "${client_args[@]}" >/dev/null
if [[ -z "${SLURM_JOB_ID:-}" && "${EWM_EVAL_DIRECT:-0}" != 1 ]]; then
    mkdir -p "$project_root/logs"
    exec sbatch --partition="${EWM_EVAL_PARTITION:-cluster02}" \
        --gres="${EWM_EVAL_GRES:-gpu:l40:1}" --nodes=1 --ntasks=1 --cpus-per-task=8 \
        --mem=64G --time="${EWM_EVAL_TIME:-08:00:00}" --job-name="ewm-eval-$task" \
        --output="$project_root/logs/ewm_${task}_eval_%j.log" \
        --error="$project_root/logs/ewm_${task}_eval_%j.log" "$script_path" "${original_args[@]}"
fi
if [[ -z "$output_dir" ]]; then
    clock="latency"; if (( ! latency )); then clock="paused"; fi
    output_dir="$checkpoint_dir/eval_piper_tasks/$task/${condition}_${rgb_mode}_${clock}/job${SLURM_JOB_ID:-local_$(date -u +%Y%m%d_%H%M%S)}"
fi
output_dir="$(realpath -m "$output_dir")"
if [[ -e "$output_dir/complete.json" ]]; then
    echo "Refusing to overwrite completed evaluation: $output_dir" >&2; exit 1
fi
mkdir -p "$output_dir"
run_dir="$(mktemp -d /tmp/ewm_tasks_eval.XXXXXX)"
ready_file="$run_dir/ready.json"
server_log="$output_dir/server.log"
server_pid=""
cleanup() {
    if [[ -n "$server_pid" ]]; then
        kill "$server_pid" 2>/dev/null || true
        wait "$server_pid" 2>/dev/null || true
    fi
    rm -rf -- "$run_dir"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
export OMP_NUM_THREADS=4 OPENBLAS_NUM_THREADS=1 PYTHONUNBUFFERED=1 OMNI_KIT_ACCEPT_EULA=YES
export OMNI_USER_CONFIG_PATH="$run_dir/config" XDG_CACHE_HOME="$run_dir/cache"
export CUDA_CACHE_PATH="$run_dir/cuda" TMPDIR="$run_dir/tmp"
mkdir -p "$OMNI_USER_CONFIG_PATH" "$XDG_CACHE_HOME" "$CUDA_CACHE_PATH" "$TMPDIR"
server="ewm_eval_server.py"
if [[ "$policy_mode" == action_only ]]; then server="ewm_action_only_eval_server.py"; fi
if [[ "$policy_mode" == rgb_action ]]; then server="ewm_rgb_action_eval_server.py"; fi
prompt="$(PYTHONPATH="$project_root/Event-DataCollection/scripts${PYTHONPATH:+:$PYTHONPATH}" \
    "$OWPY" -c 'import sys; from piper_tasks import load_task; print(load_task(sys.argv[1]).PROMPT)' "$task")"
benchmark_default=0
if [[ "${COMPILE_CORE:-false}" == true ]]; then benchmark_default=1; fi
server_args=(--warmup-iters "${WARMUP_ITERS:-$latency}" --benchmark-iters "${BENCHMARK_ITERS:-$benchmark_default}")
case "${COMPILE_CORE:-false}" in
    true) server_args+=(--compile-core) ;; false) server_args+=(--no-compile-core) ;;
    *) echo 'COMPILE_CORE must be true or false' >&2; exit 2 ;;
esac
case "${CACHE_CONTEXT_KV:-true}" in
    true) server_args+=(--cache-context-kv) ;; false) server_args+=(--no-cache-context-kv) ;;
    *) echo 'CACHE_CONTEXT_KV must be true or false' >&2; exit 2 ;;
esac
server_args+=(--compile-mode "${COMPILE_MODE:-reduce-overhead}")
case "${ALLOW_COMPILE_ACTION_ERROR:-true}" in
    true) server_args+=(--allow-compile-action-error) ;;
    false) server_args+=(--no-allow-compile-action-error) ;;
    *) echo 'ALLOW_COMPILE_ACTION_ERROR must be true or false' >&2; exit 2 ;;
esac
if [[ "$policy_mode" != action_only ]]; then
    case "${CACHE_BF16_WEIGHTS:-true}" in
        true) server_args+=(--cache-bf16-weights) ;; false) server_args+=(--no-cache-bf16-weights) ;;
        *) echo 'CACHE_BF16_WEIGHTS must be true or false' >&2; exit 2 ;;
    esac
fi
case "${COMPILE_CUDA_GRAPHS:-true}" in
    true) server_args+=(--cuda-graphs) ;; false) server_args+=(--no-cuda-graphs) ;;
    *) echo 'COMPILE_CUDA_GRAPHS must be true or false' >&2; exit 2 ;;
esac
echo "[ewm-tasks] task=$task mode=$policy_mode output=$output_dir server_log=$server_log"
"$OWPY" "$project_root/OpenWAM/scripts/eval_ewm/$server" --checkpoint-dir "$checkpoint_dir" \
    --ready-file "$ready_file" --warmup-prompt "$prompt" "${server_args[@]}" >"$server_log" 2>&1 &
server_pid=$!
for ((attempt=0; attempt<3600; attempt++)); do
    [[ -s "$ready_file" ]] && break
    if ! kill -0 "$server_pid" 2>/dev/null; then
        tail -n 50 "$server_log" >&2; exit 1
    fi
    sleep .5
done
if [[ ! -s "$ready_file" ]]; then echo 'Policy server readiness timeout' >&2; exit 1; fi
if [[ "${COMPILE_CORE:-false}" == true ]]; then
    "$OWPY" - "$ready_file" "$policy_mode" <<'PY'
import json, os, sys
metadata = json.load(open(sys.argv[1]))
if metadata.get('compile_core_active') is not True:
    raise SystemExit('Compiled evaluation requested, but the policy server fell back to eager; refusing rollout.')
if os.environ.get('COMPILE_CUDA_GRAPHS') == 'false' and metadata.get('cuda_graphs_enabled') is not False:
    raise SystemExit('CUDA Graphs were disabled, but the server did not confirm this; refusing rollout.')
if os.environ.get('CACHE_BF16_WEIGHTS') == 'false' and sys.argv[2] != 'action_only' and metadata.get('cache_bf16_weights') is not False:
    raise SystemExit('BF16 weight cache was disabled, but the server did not confirm this; refusing rollout.')
print('COMPILED_POLICY_READY', metadata.get('startup_benchmark'), flush=True)
PY
fi
if [[ "${POLICY_SERVER_PROBE:-false}" == true ]]; then
    probe_args=()
    if [[ "${COMPILE_CORE:-false}" == true ]]; then probe_args+=(--require-compiled); fi
    if [[ "${COMPILE_CUDA_GRAPHS:-true}" == false ]]; then probe_args+=(--require-no-cudagraphs); fi
    "$OWPY" "$project_root/OpenWAM/scripts/eval_ewm/check_ewm_policy_server.py" \
        --ready-file "$ready_file" --output "$output_dir/server_probe.json" \
        --prompt "$prompt" "${probe_args[@]}"
fi
"$OWPY" "$project_root/OpenWAM/scripts/eval_ewm/ewm_eval_watchdog.py" \
    --output-dir "$output_dir" --stall-timeout "${CLIENT_STALL_TIMEOUT:-720}" \
    --startup-timeout "${CLIENT_STARTUP_TIMEOUT:-900}" --max-restarts "${CLIENT_MAX_RESTARTS:-3}" -- \
    "$SIMPY" "$client" "${base_args[@]}" --ready-file "$ready_file" --output-dir "$output_dir" \
    --device cpu --headless --enable_cameras "${client_args[@]}"
if [[ ! -s "$output_dir/complete.json" ]]; then
    echo 'Client exited without complete.json' >&2; exit 1
fi
